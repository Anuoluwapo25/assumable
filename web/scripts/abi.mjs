// Regenerates src/lib/abi.ts from the Foundry build, so the app's types track
// the contracts exactly. Run `forge build` at the repo root first.
//
// The output is committed: deploying the app must not require a Solidity
// toolchain.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

const contracts = {
  backstopVaultAbi: "BackstopVault.sol/BackstopVault.json",
  stabilityPoolAbi: "IStabilityPool.sol/IStabilityPool.json",
  priceFeedAbi: "IPriceFeed.sol/IPriceFeed.json",
  // Only used by the testnet demo panel, which drives the mocks directly.
  mockMusdAbi: "MockMUSD.sol/MockMUSD.json",
  mockStabilityPoolAbi: "MockStabilityPool.sol/MockStabilityPool.json",
};

let out = "// Generated by scripts/abi.mjs from the Foundry build. Do not edit.\n";
for (const [name, path] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(join(root, "out", path), "utf8"));
  out += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}

writeFileSync(join(root, "web", "src", "lib", "abi.ts"), out);
console.log("wrote src/lib/abi.ts");
