// Regenerates the web app's ABIs from the Foundry build, so its types track
// the contracts exactly, and its network addresses from config/*.json, the
// single source of addresses. Run `forge build` at the repo root first.
//
//   node scripts/abi.mjs
//
// The output is committed: deploying the app must not require a Solidity
// toolchain.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const built = (name) =>
  JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8")).abi;

const ours = {
  trovePositionsAbi: built("TrovePositions"),
  troveAccountAbi: built("TroveAccount"),
  troveMarketAbi: built("TroveMarket"),
  cashOutModuleAbi: built("CashOutModule"),
  swapBridgeAdapterAbi: built("SwapBridgeAdapter"),
  directMusdAdapterAbi: built("DirectMUSDAdapter"),
};

// The live MUSD system's functions the app calls directly, from mezo-org/musd.
// Hand-listed rather than built: this repo only compiles the slices it needs.
const musd = {
  troveManagerAbi: [
    "function getCurrentICR(address borrower, uint256 price) view returns (uint256)",
    "function getTroveInterestRate(address borrower) view returns (uint16)",
  ],
  interestRateManagerAbi: ["function interestRate() view returns (uint16)"],
  sortedTrovesAbi: [
    "function getSize() view returns (uint256)",
    "function findInsertPosition(uint256 NICR, address prevId, address nextId) view returns (address, address)",
  ],
  hintHelpersAbi: [
    "function getApproxHint(uint256 CR, uint256 numTrials, uint256 inputRandomSeed) view returns (address hintAddress, uint256 diff, uint256 latestRandomSeed)",
  ],
  priceFeedAbi: ["function fetchPrice() view returns (uint256)"],
  borrowerOperationsAbi: [
    "function borrowingRate() view returns (uint256)",
    "function minNetDebt() view returns (uint256)",
  ],
  poolRouterAbi: [
    "struct Route { address from; address to; bool stable; address factory; }",
    "function getAmountsOut(uint256 amountIn, Route[] routes) view returns (uint256[] amounts)",
  ],
  assetsBridgeAbi: [
    "function getMinBridgeOutAmount(address mezoToken) view returns (uint256)",
    "event AssetsUnlocked(uint256 indexed unlockSequenceNumber, bytes indexed recipient, address indexed token, address sender, uint256 amount, uint8 chain)",
  ],
};

let out = "// Generated by scripts/abi.mjs. Do not edit.\n\n";
out += 'import { parseAbi } from "viem";\n';
for (const [name, abi] of Object.entries(ours)) {
  out += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
for (const [name, sigs] of Object.entries(musd)) {
  out += `\nexport const ${name} = parseAbi(${JSON.stringify(sigs, null, 2)});\n`;
}

for (const target of ["web/src/lib/abi.ts"]) {
  writeFileSync(join(root, target), out);
  console.log(`wrote ${target}`);
}

// Addresses: config/*.json, keyed by chain id.
const networks = {};
for (const file of ["mezo-testnet.json", "mezo-mainnet.json"]) {
  const net = JSON.parse(readFileSync(join(root, "config", file), "utf8"));
  networks[net.chainId] = net;
}
const nets =
  "// Generated by scripts/abi.mjs from config/*.json. Do not edit.\n\n" +
  `export const networks = ${JSON.stringify(networks, null, 2)} as const;\n`;
writeFileSync(join(root, "web/src/lib/networks.ts"), nets);
console.log("wrote web/src/lib/networks.ts");
